def sum_of_number(first_number, second_number):
	return first_number + second_number

def exponential_of_number(first_number, second_number):
	return first_number ** second_number

def subtraction_of_number(first_number, second_number):
	return first_number - second_number

def multiplication_of_number(first_number, second_number):
	return first_number * second_number

def division_of_number(first_number, second_number):
	return first_number / second_number


print(sum_of_number(13,6))
print(exponential_of_number(13,6))
print(subtraction_of_number(13,6))
print(multiplication_of_number(13,6))
print(division_of_number(13,6))



